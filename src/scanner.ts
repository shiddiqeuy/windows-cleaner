export async function scanTargetCategory(
  category: TargetCategory,
  minAgeMs: number,
  isAdmin: boolean
): Promise<CategoryScanResult> {
  const scannedFiles: ScannedFile[] = [];
  let totalSizeBytes = 0;
  let accessDenied = false;
  let skippedLockedCount = 0;

  const now = Date.now();
  const cutoffTime = now - minAgeMs;

  for (const targetPath of category.paths) {
    if (!fs.existsSync(targetPath)) continue;

    try {
      await traverseDirectory(targetPath, category, cutoffTime, scannedFiles);
    } catch (err: any) {
      if (err.code === 'EACCES' || err.code === 'EPERM') {
        accessDenied = true;
      }
    }
  }

  for (const file of scannedFiles) {
    totalSizeBytes += file.sizeBytes;
    if (file.isLocked) {
      skippedLockedCount++;
    }
  }

  return {
    category,
    files: scannedFiles,
    totalSizeBytes,
    candidateCount: scannedFiles.length,
    requiresAdmin: category.requiresAdmin,
    accessDenied,
    skippedLockedCount
  };
}

async function traverseDirectory(
  dirPath: string,
  category: TargetCategory,
  cutoffTime: number,
  results: ScannedFile[],
  depth = 0
) {
  if (depth > 10) return; // Prevent excessive recursion depth

  let entries: fs.Dirent[];
  try {
    entries = await fs.promises.readdir(dirPath, { withFileTypes: true });
  } catch (err: any) {
    return;
  }

  for (const entry of entries) {
    const fullPath = path.join(dirPath, entry.name);

    try {
      if (entry.isDirectory()) {
        await traverseDirectory(fullPath, category, cutoffTime, results, depth + 1);
      } else if (entry.isFile()) {
        // Pattern filter check if specified
        if (category.patterns && category.patterns.length > 0) {
          const matches = category.patterns.some((pattern) => pattern.test(entry.name));
          if (!matches) continue;
        }

        const stat = await fs.promises.stat(fullPath);

        // Min-age filter
        if (stat.mtimeMs <= cutoffTime) {
          results.push({
            filePath: fullPath,
            sizeBytes: stat.size,
            lastModified: stat.mtime,
            categoryId: category.id
          });
        }
      }
    } catch {
      // Ignore unreadable individual files
    }
  }
}

export async function runFullScan(
  selectedCategoryIds: CategoryId[] | 'all',
  minAgeMs: number
): Promise<ScanSummary> {
  const startTime = Date.now();
  const isAdmin = checkIsAdmin();
  const categories = getTargetCategories();

  const filteredCategories = selectedCategoryIds === 'all'
    ? categories
    : categories.filter((c) => selectedCategoryIds.includes(c.id));

  const results: CategoryScanResult[] = [];
  let totalSizeBytes = 0;
  let totalFileCount = 0;

  for (const category of filteredCategories) {
    const scanResult = await scanTargetCategory(category, minAgeMs, isAdmin);
    results.push(scanResult);
    totalSizeBytes += scanResult.totalSizeBytes;
    totalFileCount += scanResult.candidateCount;
  }

  const scanTimeMs = Date.now() - startTime;

  return {
    categories: results,
    totalSizeBytes,
    totalFileCount,
    scanTimeMs,
    minAgeMs,
    isAdmin
  };
}
